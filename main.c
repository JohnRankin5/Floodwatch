uint32_t Read_HCSR04(void)
{
    uint32_t start_time = 0, stop_time = 0;
//    return 1000; // 1000 timer ticks


    // Trigger 10 us pulse
    HAL_GPIO_WritePin(GPIOA, GPIO_PIN_10, GPIO_PIN_SET);
    for(volatile int i = 0; i < 800; i++) __NOP();  // ~10 us
    HAL_GPIO_WritePin(GPIOA, GPIO_PIN_10, GPIO_PIN_RESET);

    uint32_t start_counter = __HAL_TIM_GET_COUNTER(&htim1);

    // Wait for Echo HIGH
    while(HAL_GPIO_ReadPin(GPIOA, GPIO_PIN_9) == GPIO_PIN_RESET)
    {
        if((__HAL_TIM_GET_COUNTER(&htim1) - start_counter) > 60000)
            return 0xFFFFFFFF; // timeout ~60ms
    }
    start_time = __HAL_TIM_GET_COUNTER(&htim1);

    // Wait for Echo LOW
    start_counter = __HAL_TIM_GET_COUNTER(&htim1);
    while(HAL_GPIO_ReadPin(GPIOA, GPIO_PIN_9) == GPIO_PIN_SET)
    {
        if((__HAL_TIM_GET_COUNTER(&htim1) - start_counter) > 60000)
            return 0xFFFFFFFF; // timeout ~60ms
    }
    stop_time = __HAL_TIM_GET_COUNTER(&htim1);

    if(stop_time < start_time)
        stop_time += 65535;

    printf("Start: %lu, Stop: %lu\r\n", start_time, stop_time);
    return stop_time - start_time;
}



uint32_t Retrieve_Distance(void)
{
    uint32_t duration_ticks = Read_HCSR04();
    if(duration_ticks == 0xFFFFFFFF)
        return 0; // Timeout or no echo

    // Calculate tick time in microseconds
    // TIM1 clock is typically PCLK2 * 2 if APB2 prescaler != 1
    uint32_t tim_clk = HAL_RCC_GetPCLK2Freq();
    float tick_time_us = (float)(htim1.Init.Prescaler + 1) / tim_clk * 1e6f;

    float duration_us = duration_ticks * tick_time_us;

    // Convert to distance in cm (speed of sound 0.0343 cm/us)
    return (uint32_t)((duration_us * 0.0343f) / 2.0f);
}

